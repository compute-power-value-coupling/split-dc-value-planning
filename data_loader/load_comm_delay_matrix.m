%% =========================================================================
%  load_comm_delay_matrix.m  —  通信时延矩阵
%  
%  7x7对称矩阵, 行列顺序: 北京/上海/广州/成渝/内蒙/宁夏/甘肃
%  数值: 光纤单向传播时延(ms), 基于实际光纤路由距离与等效传播速率(2e5km/s)
%% =========================================================================
function comm_delay = load_comm_delay_matrix(P)

%      京   沪   广   渝   蒙   宁   甘
D = [   0   11   28   19    8   18   22;    % 北京
       11    0   18   17   19   28   30;    % 上海
       28   18    0   15   30   33   35;    % 广州
       19   17   15    0   22   18   20;    % 成渝
        8   19   30   22    0   14   17;    % 内蒙古
       18   28   33   18   14    0    8;    % 宁夏
       22   30   35   20   17    8    0];   % 甘肃

% 对称性验证
if max(max(abs(D - D'))) > 1e-6
    error('通信时延矩阵不对称!');
end

% 三角不等式验证(放宽容差因离散数值)
for i = 1:7
    for j = 1:7
        for k = 1:7
            if D(i,j) > D(i,k) + D(k,j) + 0.1
                warning('三角不等式违反: D(%d,%d)=%d > D(%d,%d)+D(%d,%d)=%d', ...
                    i,j,D(i,j),i,k,k,j,D(i,k)+D(k,j));
            end
        end
    end
end

comm_delay = D;
fprintf('       通信时延矩阵: 7x7对称, 最大%dms, 平均%.1fms\n', ...
    max(D(:)), mean(D(D>0)));
end
